/**
 * Generate Tauri desktop icon sets using `tauri icon`.
 *
 * Source: `frontend/public/large-icon.png` (the 1024x1024 source sharing the mark
 * with `favicon.svg` from `generate-icons.mjs`).
 * Writes to `src-tauri/icons/` and keeps only the desktop icon formats.
 */

import { spawnSync } from 'node:child_process'
import { rm } from 'node:fs/promises'
import { glob } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const TAURI_ROOT = join(__dirname, '..')
const REPO_ROOT = join(TAURI_ROOT, '..')
const SOURCE_ICON = join(REPO_ROOT, 'frontend', 'public', 'large-icon.png')
const OUTPUT_DIR = join(TAURI_ROOT, 'src-tauri', 'icons')

export async function generateIcons() {
  const r = spawnSync('npx', ['tauri', 'icon', SOURCE_ICON, '-o', OUTPUT_DIR], {
    cwd: TAURI_ROOT,
    stdio: 'inherit',
  })
  if (r.status !== 0) {
    throw new Error(`tauri icon failed with exit code ${r.status}`)
  }

  // Remove non-desktop assets generated by default
  await rm(join(OUTPUT_DIR, 'android'), { recursive: true, force: true })
  await rm(join(OUTPUT_DIR, 'ios'), { recursive: true, force: true })

  for await (const entry of glob(join(OUTPUT_DIR, '{Square*,Store*}'))) {
    await rm(entry, { force: true })
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await generateIcons()
}
